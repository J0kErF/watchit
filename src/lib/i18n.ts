/**
 * Interface language. English is the source: `t()` looks the English text up in the Arabic or Hebrew
 * table and falls back to the English when there's no translation. `{name}` placeholders are filled
 * in from `vars`. The choice is a cookie, set by the switch in the navbar.
 */
export type Lang = "en" | "ar" | "he";

/** The languages in the navbar switch, each labeled in its own language. */
export const LANGS: { value: Lang; label: string }[] = [
  { value: "en", label: "EN" },
  { value: "ar", label: "عربي" },
  { value: "he", label: "עברית" },
];

export const LANG_COOKIE = "jawy-lang";

export const parseLang = (value?: string | null): Lang => (value === "ar" || value === "he" ? value : "en");

export const langDir = (lang: Lang) => (lang === "en" ? "ltr" : "rtl");

/** The TMDb `language` parameter for an interface language. */
export const tmdbLanguage = (lang: Lang) => (lang === "en" ? "en-US" : lang);

export function t(lang: Lang, text: string, vars?: Record<string, string | number>) {
  const s = lang === "en" ? text : (TABLES[lang][text] ?? text);
  return vars ? s.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match)) : s;
}

/** Whether `t()` has a translation for the text, rather than falling back to the English. */
export const translated = (lang: Lang, text: string) => lang === "en" || text in TABLES[lang];

